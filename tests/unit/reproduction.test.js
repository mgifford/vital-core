import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { chromium } from 'playwright';
import {
  reproductionPlan,
  executeReproduction,
  playwrightTestFor,
  isReplayableSelector,
  REPRODUCTION_EXIT_CODES,
} from '../../src/lib/reproduction.js';
import { runReproduction } from '../../src/lib/reproduction-runner.js';

const ROOT = path.resolve(new URL('../..', import.meta.url).pathname);
const FIXTURE = pathToFileURL(path.join(ROOT, 'tests', 'fixtures', 'walsall-consent.html')).href;
const AXE_SOURCE = fs.readFileSync(new URL('../../node_modules/axe-core/axe.min.js', import.meta.url), 'utf8');

const bug = (over = {}) => ({
  instance_id: 'VS-repro01',
  pattern_id: 'VS-repopat',
  url: FIXTURE,
  selector: '.qc-cmp2-toggle',
  engine_key: 'axe-core',
  rule_id: 'button-name',
  element: { available: true, selector: '.qc-cmp2-toggle', tag: 'button' },
  browser_context: { viewport: { width: 1280, height: 800 }, color_scheme: 'light', forced_colors: 'none', reduced_motion: 'no-preference', locale: 'en' },
  ...over,
});

const plan = (over = {}) => reproductionPlan(bug(over));

test('reproduction plan: ready evidence carries the selector, rule and browser context', () => {
  const p = plan();
  assert.equal(p.status, 'not_attempted');
  assert.equal(p.locator.strategy, 'css');
  assert.equal(p.locator.value, '.qc-cmp2-toggle');
  assert.deepEqual(p.rule, { engine: 'axe-core', id: 'button-name', impact: null });
  assert.deepEqual(p.context, {
    viewport: { width: 1280, height: 800 },
    colorScheme: 'light',
    forcedColors: 'none',
    reducedMotion: 'no-preference',
    locale: 'en',
  });
  assert.deepEqual(p.steps, []);
});

test('reproduction plan: missing or unsafe evidence is unavailable with a reason', () => {
  assert.equal(plan({ element: null }).status, 'unavailable');
  assert.equal(plan({ element: { available: false, reason: 'not-found' } }).reason, 'element-not-found-at-scan');
  assert.equal(plan({ element: { available: true }, selector: null }).reason, 'selector-not-replayable');
  assert.equal(plan({ selector: 'text: "PRIVATE"' }).reason, 'selector-not-replayable');
  assert.equal(plan({ url: 'https://example.gov/a?token=[REDACTED]' }).reason, 'url-redacted-for-publication');
  assert.equal(plan({ engine_key: 'alfa' }).reason, 'only-axe-core-findings-can-be-replayed');
  assert.equal(isReplayableSelector('button[aria-label="Opt-Outs"]'), true);
  assert.equal(isReplayableSelector('input[value="PRIVATE"]'), false);
});

test('playwrightTestFor refuses an unavailable plan and emits a runnable standalone script', () => {
  assert.throws(() => playwrightTestFor({ status: 'unavailable', reason: 'x' }), /unavailable/);
  const code = playwrightTestFor(plan(), { generatedAt: '2026-11-06T00:00:00.000Z' });
  assert.match(code, /^#!\/usr\/bin\/env node/);
  assert.match(code, /Generated by vital-core, 2026-11-06T00:00:00.000Z/);
  assert.match(code, /"id": "button-name"/);
  assert.match(code, /"\.qc-cmp2-toggle"/);
  assert.match(code, /executeReproduction/);
  assert.match(code, /process\.exit\(EXIT_CODES\[result\.status\]/);
  assert.equal(REPRODUCTION_EXIT_CODES.reproduced, 0);
  assert.equal(REPRODUCTION_EXIT_CODES.ambiguous_locator, 3);
});

test('executeReproduction distinguishes reproduced, not reproduced, missing, ambiguous and fails-elsewhere', async () => {
  const browser = await chromium.launch();
  try {
    const run = async (over) => {
      const page = await browser.newPage();
      try {
        await page.goto(FIXTURE, { waitUntil: 'load' });
        return await executeReproduction(page, AXE_SOURCE, plan(over));
      } finally {
        await page.close();
      }
    };

    const reproduced = await run({});
    assert.equal(reproduced.status, 'reproduced');
    assert.equal(reproduced.matches, 1);

    // The toggle has no text; the button-name rule does not apply to contrast.
    const notReproduced = await run({ rule_id: 'color-contrast' });
    assert.equal(notReproduced.status, 'not_reproduced');

    const missing = await run({ selector: '#does-not-exist' });
    assert.equal(missing.status, 'locator_not_found');

    const ambiguous = await run({ selector: 'button' });
    assert.equal(ambiguous.status, 'ambiguous_locator');
    assert.ok(ambiguous.matches > 1);

    // The list rule fails on the page, but on a different element.
    const elsewhere = await run({ selector: '#orphaned-preference', rule_id: 'list' });
    assert.equal(elsewhere.status, 'not_reproduced');
    assert.equal(elsewhere.rule_fails_elsewhere, true);

    const dialogGone = await run({ selector: '#does-not-exist', semantic_context: { in_dialog: true } });
    assert.equal(dialogGone.status, 'interaction_state_unavailable');

    const unknownRule = await run({ rule_id: 'definitely-not-an-axe-rule' });
    assert.equal(unknownRule.status, 'rule_or_engine_changed');
  } finally {
    await browser.close();
  }
});

test('runReproduction runs the plan and returns the same shape as the generated script', async () => {
  const result = await runReproduction(plan());
  assert.equal(result.status, 'reproduced');
  assert.equal(result.rule_id, 'button-name');
  assert.equal(result.matches, 1);
  const unavailable = await runReproduction({ status: 'unavailable', reason: 'x' });
  assert.deepEqual(unavailable, { status: 'unavailable', reason: 'x' });
});

test('the generated script runs standalone and exits 0 only when reproduced', () => {
  const file = path.join(ROOT, `.tmp-reproduction-${process.pid}.spec.mjs`);
  fs.writeFileSync(file, playwrightTestFor(plan()));
  try {
    const stdout = execFileSync(process.execPath, [file], { cwd: ROOT, encoding: 'utf8', timeout: 60000 });
    const result = JSON.parse(stdout);
    assert.equal(result.status, 'reproduced');
    assert.equal(result.rule_id, 'button-name');
  } finally {
    fs.rmSync(file, { force: true });
  }
});
